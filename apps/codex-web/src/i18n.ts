export const language = navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
export const t: Messages = language === "zh" ? zh : en;

const relative = new Intl.RelativeTimeFormat(language, { numeric: "auto", style: "narrow" });

export function ago(seconds: number): string {
	const minutes = Math.round((seconds - Date.now() / 1000) / 60);
	if (Math.abs(minutes) < 60) {
		return relative.format(minutes, "minute");
	}
	const hours = Math.round(minutes / 60);
	return Math.abs(hours) < 24 ? relative.format(hours, "hour") : relative.format(Math.round(hours / 24), "day");
}

export function duration(ms: number): string {
	const seconds = Math.round(ms / 1000);
	if (seconds < 60) {
		return language === "zh" ? `${seconds} 秒` : `${seconds}s`;
	}
	const minutes = Math.floor(seconds / 60);
	return language === "zh" ? `${minutes} 分 ${seconds % 60} 秒` : `${minutes}m ${seconds % 60}s`;
}

export function compactNumber(value: number): string {
	return new Intl.NumberFormat(language, { notation: "compact", maximumFractionDigits: 1 }).format(value);
}

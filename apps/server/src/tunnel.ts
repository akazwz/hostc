/** The Worker forwards authenticated connect requests to this URL. Public requests never have this host. */
export const CONNECT_URL = "http://hostc.internal/connect";
/**
 * Internal marker on 404/429 responses generated by a missing or terminated tunnel, so the Worker can
 * negatively cache expired ids without ever caching a 404 returned by a user's local server.
 * Stripped from local responses in `publicResponseHeaders` and removed by the Worker before replying.
 */
export const TUNNEL_MISSING_HEADER = "x-hostc-tunnel-missing";

export type InitTunnelOptions = {
	tier?: PlanTier;
	limits?: Partial<TunnelLimits>;
};

const TUNNEL_KEY = "tunnel";
const USAGE_KEY = "usage";
/** Stream ids at or above this value have not been handed out yet. Reserved in blocks to avoid a write per request. */
const STREAM_CEILING_KEY = "streamCeiling";
const STREAM_ID_BLOCK = 1024;

const WS_RATE_WINDOW_MS = 10_000;
const STORAGE_FRAME_CHECKPOINT = 1_000;
const STORAGE_WS_MSG_CHECKPOINT = 250;
const STORAGE_WS_CONN_CHECKPOINT = 10;
const STORAGE_BYTES_CHECKPOINT = 8 * 1024 * 1024;
const ATTACHMENT_FRAME_CHECKPOINT = 16;
const ATTACHMENT_BYTES_CHECKPOINT = 256 * 1024;

type UsageCounters = {
	totalFrames: number;
	totalBytes: number;
	publicWsConnections: number;
	publicWsMessages: number;
	publicWsBytes: number;
};

type TunnelRecord = {
	createdAt: number;
	tier?: PlanTier;
	limits?: Partial<TunnelLimits>;
};

type TunnelState = {
	createdAt: number;
	tier: PlanTier;
	limits: TunnelLimits;
};

type RateWindow = {
	windowStart: number;
	prevCount: number;
	currCount: number;
};

/**
 * Everything needed to route WebSocket traffic lives in socket attachments and
 * tags, so the object can hibernate while a tunnel or a public WebSocket is idle.
 */
type ClientAttachment = { kind: "client"; since: number; retired?: true; usage?: UsageCounters };
type PublicAttachment = { kind: "public"; stream: number };
type Attachment = ClientAttachment | PublicAttachment;

type HeadResult = { ok: true; head: HeadMessage; headers: Headers } | { ok: false; page: PageOptions };

/** In-flight public HTTP request. Lives only in memory: the object stays awake while it runs. */
type HttpStream = {
	id: number;
	settleHead: (result: HeadResult) => void;
	headReceived: boolean;
	/** Request body bytes we may still send to the client. */
	sendCredit: number;
	wakeUploader: (() => void) | null;
	uploading: boolean;
	/** Response body bytes the client may still send to us. */
	receiveCredit: number;
	/** Response window granted to the client, widened while it holds the response back. */
	window: GrowingWindow;
	queue: Uint8Array[];
	pulling: boolean;
	ended: boolean;
	controller: ReadableStreamDefaultController<Uint8Array> | null;
	done: boolean;
};

/** Public WebSocket upgrade waiting for the local server to accept or reject it. */
type PendingWebSocket = {
	offered: string[];
	settle: (response: Response) => void;
};

/** One Durable Object per tunnel. */
export class Tunnel extends DurableObject<Env> {
	private state: TunnelState | null = null;
	private usage: UsageCounters = emptyUsage();
	private lastStoredUsage: UsageCounters = emptyUsage();
	private lastAttachmentUsage: UsageCounters = emptyUsage();
	private wsRate: RateWindow = { windowStart: 0, prevCount: 0, currCount: 0 };
	private terminating = false;
	private streamIdsLoaded: Promise<void> | undefined;
	private nextStream = 1;
	private streamCeiling = 0;
	private readonly http = new Map<number, HttpStream>();
	private readonly pendingWebSockets = new Map<number, PendingWebSocket>();
	/** Requests waiting for a free stream, oldest first. Called with false when they should stop waiting. */
	private readonly waiting: ((free: boolean) => void)[] = [];
	/** Response window beyond STREAM_WINDOW_BYTES, shared by the streams of this tunnel. */
	private readonly windowBudget = new WindowBudget();

	constructor(ctx: DurableObjectState, env: Env) {
		super(ctx, env);
		// Heartbeats are answered by the runtime without waking the object.
		ctx.setWebSocketAutoResponse(new WebSocketRequestResponsePair(PING, PONG));
		// Load persisted state before handling fetch/webSocketMessage/alarm so WebSocket frames stay strictly ordered.
		void ctx.blockConcurrencyWhile(() => this.loadState());
	}

	/** Called by the Worker right after it picks a new tunnel id. */
	async init(options?: InitTunnelOptions): Promise<void> {
		const tier = options?.tier ?? "free";
		const limits: TunnelLimits = { ...limitsForTier(tier), ...options?.limits };
		const createdAt = Date.now();
		this.state = { createdAt, tier, limits };
		this.usage = emptyUsage();
		this.lastStoredUsage = emptyUsage();
		this.lastAttachmentUsage = emptyUsage();
		this.wsRate = { windowStart: 0, prevCount: 0, currCount: 0 };
		this.terminating = false;
		this.streamIdsLoaded = undefined;
		this.nextStream = 1;
		this.streamCeiling = 0;
		await this.ctx.storage.put(TUNNEL_KEY, { createdAt, tier, limits } satisfies TunnelRecord);
		await this.ctx.storage.delete(USAGE_KEY);
		await this.ctx.storage.setAlarm(this.nextAlarmAt(CONNECT_GRACE_MS));
	}

	override async fetch(request: Request): Promise<Response> {
		const isConnect = request.url === CONNECT_URL;
		if (!this.state) {
			return this.missingResponse(request, isConnect);
		}
		const durationReason = this.durationLimitBreach();
		if (durationReason) {
			await this.terminateLimit(durationReason);
			return isConnect
				? this.missingResponse(request, true)
				: this.refuseLimit(request, request.headers.get("upgrade")?.toLowerCase() === "websocket");
		}
		if (isConnect) {
			return this.acceptClient();
		}
		return request.headers.get("upgrade")?.toLowerCase() === "websocket"
			? this.proxyWebSocket(request)
			: this.proxyHttp(request);
	}

	override async alarm(): Promise<void> {
		const durationReason = this.durationLimitBreach();
		if (durationReason) {
			await this.terminateLimit(durationReason);
			return;
		}
		const client = this.client();
		if (client && !isStale(this.ctx, client)) {
			// Connected: check the heartbeat again later.
			await this.ctx.storage.setAlarm(this.nextAlarmAt(RECONNECT_GRACE_MS));
			return;
		}
		if (client) {
			// The connection looks open but the client stopped pinging.
			this.retire(client, 1001, "heartbeat timeout");
			await this.clientGone(1001);
			return;
		}
		await this.expire();
	}

	override async webSocketMessage(ws: WebSocket, message: string | ArrayBuffer): Promise<void> {
		if (!this.state || this.terminating) {
			return;
		}
		const durationReason = this.durationLimitBreach();
		if (durationReason) {
			await this.terminateLimit(durationReason);
			return;
		}
		const attachment = attachmentOf(ws);
		if (attachment?.kind === "public") {
			const frameBreach = this.recordFrame();
			if (frameBreach) {
				await this.terminateLimit(frameBreach);
				return;
			}
			const breach = this.fromPublic(ws, attachment.stream, message);
			if (breach) {
				await this.terminateLimit(breach);
				return;
			}
			this.syncUsage();
			return;
		}
		if (attachment?.kind !== "client" || attachment.retired || typeof message === "string") {
			return;
		}
		if (attachment.usage) {
			this.usage = maxUsage(this.usage, normalizeUsage(attachment.usage));
		}
		const frameBreach = this.recordFrame();
		if (frameBreach) {
			await this.terminateLimit(frameBreach);
			return;
		}
		try {
			const breach = this.fromClient(decodeFrame(new Uint8Array(message)));
			if (breach) {
				await this.terminateLimit(breach);
				return;
			}
			this.syncUsage();
		} catch (error) {
			if (!(error instanceof ProtocolError)) {
				throw error;
			}
			this.retire(ws, CLOSE_PROTOCOL_ERROR, error.message);
			await this.clientGone(CLOSE_PROTOCOL_ERROR);
		}
	}

	override async webSocketClose(ws: WebSocket, code: number, reason: string): Promise<void> {
		await this.socketGone(ws, code, reason);
	}

	override async webSocketError(ws: WebSocket): Promise<void> {
		await this.socketGone(ws, 1006, "");
	}

	private async loadState(): Promise<void> {
		const stored = await this.ctx.storage.get([TUNNEL_KEY, USAGE_KEY]);
		const record = stored.get(TUNNEL_KEY) as TunnelRecord | undefined;
		if (!record) {
			this.state = null;
			this.usage = emptyUsage();
			this.lastStoredUsage = emptyUsage();
			this.lastAttachmentUsage = emptyUsage();
			return;
		}
		const tier = record.tier ?? "free";
		const limits: TunnelLimits = { ...limitsForTier(tier), ...record.limits };
		this.state = { createdAt: record.createdAt, tier, limits };
		const saved = normalizeUsage(stored.get(USAGE_KEY) as Partial<UsageCounters> | undefined);
		let merged = { ...saved };
		for (const ws of this.ctx.getWebSockets("client")) {
			const attachment = attachmentOf(ws);
			if (attachment?.kind === "client" && attachment.usage) {
				merged = maxUsage(merged, normalizeUsage(attachment.usage));
			}
		}
		this.usage = merged;
		this.lastStoredUsage = { ...saved };
		this.lastAttachmentUsage = { ...merged };
	}

	private currentLimits(): TunnelLimits {
		return this.state?.limits ?? FREE_LIMITS;
	}

	private durationLimitBreach(): string | null {
		const state = this.state;
		if (!state || state.limits.maxDurationMs === null) {
			return null;
		}
		if (Date.now() < state.createdAt + state.limits.maxDurationMs) {
			return null;
		}
		return durationLimitReason(state.limits.maxDurationMs);
	}

	private nextAlarmAt(baseDelayMs: number): number {
		const candidate = Date.now() + baseDelayMs;
		const state = this.state;
		if (!state || state.limits.maxDurationMs === null) {
			return candidate;
		}
		return Math.min(candidate, state.createdAt + state.limits.maxDurationMs);
	}

	private recordFrame(): string | null {
		this.usage.totalFrames += 1;
		const maxFrames = this.currentLimits().maxTotalFrames;
		if (maxFrames !== null && this.usage.totalFrames > maxFrames) {
			return "Tunnel frame limit reached.";
		}
		return null;
	}

	private recordTransferBytes(bytes: number): string | null {
		if (bytes <= 0) {
			return null;
		}
		this.usage.totalBytes += bytes;
		const maxBytes = this.currentLimits().maxBytes;
		if (maxBytes !== null && this.usage.totalBytes > maxBytes) {
			return "Tunnel transfer limit reached.";
		}
		return null;
	}

	private recordPublicWsMessage(bytes: number): string | null {
		const limits = this.currentLimits();
		this.usage.publicWsMessages += 1;
		this.usage.publicWsBytes += bytes;
		const totalByteBreach = this.recordTransferBytes(bytes);
		if (totalByteBreach) {
			return totalByteBreach;
		}
		if (limits.maxPublicWebSocketMessages !== null && this.usage.publicWsMessages > limits.maxPublicWebSocketMessages) {
			return "Tunnel WebSocket message limit reached.";
		}
		if (limits.maxPublicWebSocketBytes !== null && this.usage.publicWsBytes > limits.maxPublicWebSocketBytes) {
			return "Tunnel WebSocket transfer limit reached.";
		}
		if (
			limits.maxPublicWebSocketMessagesPer10s !== null &&
			this.recordPublicWsRate(Date.now(), limits.maxPublicWebSocketMessagesPer10s)
		) {
			return "Tunnel WebSocket message rate limit exceeded.";
		}
		return null;
	}

	private recordPublicWsRate(now: number, maxPer10s: number): boolean {
		if (this.wsRate.windowStart === 0) {
			this.wsRate.windowStart = now;
			this.wsRate.prevCount = 0;
			this.wsRate.currCount = 1;
			return 1 > maxPer10s;
		}
		const elapsed = now - this.wsRate.windowStart;
		if (elapsed >= WS_RATE_WINDOW_MS * 2) {
			this.wsRate.windowStart = now;
			this.wsRate.prevCount = 0;
			this.wsRate.currCount = 1;
		} else if (elapsed >= WS_RATE_WINDOW_MS) {
			this.wsRate.windowStart += WS_RATE_WINDOW_MS;
			this.wsRate.prevCount = this.wsRate.currCount;
			this.wsRate.currCount = 1;
		} else {
			this.wsRate.currCount += 1;
		}
		const intoCurrent = Math.min(Math.max(now - this.wsRate.windowStart, 0), WS_RATE_WINDOW_MS);
		const weight = 1 - intoCurrent / WS_RATE_WINDOW_MS;
		const estimated = this.wsRate.prevCount * weight + this.wsRate.currCount;
		return estimated > maxPer10s;
	}

	/**
	 * Keeps usage accurate across hibernation via client socket attachment (zero storage cost)
	 * and checkpoints to storage in coarse batches so reconnects cannot reset counters.
	 */
	private syncUsage(forceStorage = false): void {
		if (!this.state || this.terminating) {
			return;
		}
		const client = this.client();
		const attachmentDirty =
			this.usage.publicWsConnections !== this.lastAttachmentUsage.publicWsConnections ||
			this.usage.publicWsMessages !== this.lastAttachmentUsage.publicWsMessages ||
			this.usage.totalFrames - this.lastAttachmentUsage.totalFrames >= ATTACHMENT_FRAME_CHECKPOINT ||
			this.usage.totalBytes - this.lastAttachmentUsage.totalBytes >= ATTACHMENT_BYTES_CHECKPOINT;
		if (client && attachmentDirty) {
			const current = attachmentOf(client);
			if (current?.kind === "client" && !current.retired) {
				client.serializeAttachment({ ...current, usage: { ...this.usage } } satisfies ClientAttachment);
				this.lastAttachmentUsage = { ...this.usage };
			}
		}

		const storageDirty =
			forceStorage ||
			this.usage.totalFrames - this.lastStoredUsage.totalFrames >= STORAGE_FRAME_CHECKPOINT ||
			this.usage.publicWsMessages - this.lastStoredUsage.publicWsMessages >= STORAGE_WS_MSG_CHECKPOINT ||
			this.usage.publicWsConnections - this.lastStoredUsage.publicWsConnections >= STORAGE_WS_CONN_CHECKPOINT ||
			this.usage.totalBytes - this.lastStoredUsage.totalBytes >= STORAGE_BYTES_CHECKPOINT;
		if (storageDirty) {
			this.lastStoredUsage = { ...this.usage };
			void this.ctx.storage.put(USAGE_KEY, { ...this.usage } satisfies UsageCounters);
		}
	}

	private async terminateLimit(reason: string): Promise<void> {
		if (this.terminating || !this.state) {
			return;
		}
		this.terminating = true;
		this.recordError("Limit reached", reason);
		const client = this.client();
		if (client) {
			this.retire(client, CLOSE_LIMIT_REACHED, reason);
		}
		await this.expire();
	}

	private missingResponse(request: Request, isConnect: boolean): Response {
		const response = isConnect
			? Response.json({ error: "Tunnel not found" }, { status: 404 })
			: errorResponse(request, pages.notFound);
		response.headers.set(TUNNEL_MISSING_HEADER, "1");
		return response;
	}

	private refuseLimit(request: Request, websocket: boolean): Response {
		const response = websocket
			? new Response(pages.limitReached.title, { status: pages.limitReached.status })
			: errorResponse(request, pages.limitReached);
		response.headers.set(TUNNEL_MISSING_HEADER, "1");
		return response;
	}

	private async socketGone(ws: WebSocket, code: number, reason: string): Promise<void> {
		// Complete the close handshake; hibernatable sockets are left in CLOSING otherwise.
		safeClose(ws, code, reason);
		const attachment = attachmentOf(ws);
		if (attachment?.kind === "public") {
			this.sendFrame(FrameType.End, attachment.stream, encodeClose({ code, reason }));
			this.wakeWaiting();
			return;
		}
		if (attachment?.kind === "client" && !attachment.retired) {
			if (attachment.usage) {
				this.usage = maxUsage(this.usage, normalizeUsage(attachment.usage));
			}
			ws.serializeAttachment({ ...attachment, retired: true } satisfies ClientAttachment);
			await this.clientGone(code);
		}
	}

	// ---------------------------------------------------------------------------
	// Client connection

	private async acceptClient(): Promise<Response> {
		for (const old of this.ctx.getWebSockets("client")) {
			this.retire(old, CLOSE_REPLACED, "replaced by a new connection");
		}
		this.failAll();

		const [client, server] = Object.values(new WebSocketPair()) as [WebSocket, WebSocket];
		this.ctx.acceptWebSocket(server, ["client"]);
		server.serializeAttachment({
			kind: "client",
			since: Date.now(),
			usage: { ...this.usage },
		} satisfies ClientAttachment);
		this.lastAttachmentUsage = { ...this.usage };
		await this.ctx.storage.setAlarm(this.nextAlarmAt(RECONNECT_GRACE_MS));
		return new Response(null, { status: 101, webSocket: client });
	}

	/** The current client socket, if any. */
	private client(): WebSocket | undefined {
		return this.ctx.getWebSockets("client").find((ws) => {
			const attachment = attachmentOf(ws);
			return attachment?.kind === "client" && !attachment.retired && ws.readyState === WebSocket.OPEN;
		});
	}

	/** The current client, unless it has stopped answering heartbeats. */
	private async liveClient(): Promise<WebSocket | undefined> {
		const client = this.client();
		if (client && isStale(this.ctx, client)) {
			this.retire(client, 1001, "heartbeat timeout");
			await this.clientGone(1001);
			return undefined;
		}
		return client;
	}

	/** Marks a client socket as no longer current, then closes it. Its later events are ignored. */
	private retire(ws: WebSocket, code: number, reason: string): void {
		const attachment = attachmentOf(ws);
		if (attachment?.kind === "client") {
			ws.serializeAttachment({ ...attachment, retired: true } satisfies ClientAttachment);
		}
		safeClose(ws, code, reason);
	}

	private async clientGone(code: number): Promise<void> {
		this.failAll();
		if (code === CLOSE_SHUTDOWN) {
			await this.expire();
			return;
		}
		if (this.state) {
			this.lastStoredUsage = { ...this.usage };
			await this.ctx.storage.put(USAGE_KEY, { ...this.usage } satisfies UsageCounters);
			await this.ctx.storage.setAlarm(this.nextAlarmAt(RECONNECT_GRACE_MS));
		}
	}

	private async expire(): Promise<void> {
		for (const ws of this.ctx.getWebSockets()) {
			this.retire(ws, 1001, "tunnel expired");
		}
		this.failAll();
		this.state = null;
		this.usage = emptyUsage();
		this.lastStoredUsage = emptyUsage();
		this.lastAttachmentUsage = emptyUsage();
		this.wsRate = { windowStart: 0, prevCount: 0, currCount: 0 };
		this.streamIdsLoaded = undefined;
		this.nextStream = 1;
		this.streamCeiling = 0;
		this.terminating = false;
		// Also deletes the alarm (compatibility date >= 2026-02-24).
		await this.ctx.storage.deleteAll();
	}

	/** Ends every stream. The client's local sockets and requests are gone with its connection. */
	private failAll(): void {
		for (const stream of this.http.values()) {
			this.fail(stream, pages.offline);
		}
		for (const [id, pending] of this.pendingWebSockets) {
			this.forgetPending(id);
			pending.settle(this.refuseWebSocket(pages.offline));
		}
		for (const ws of this.ctx.getWebSockets("public")) {
			safeClose(ws, 1001, "tunnel disconnected");
		}
	}

	private fromClient(frame: Frame): string | null {
		const { stream: id, payload } = frame;
		const http = this.http.get(id);
		switch (frame.type) {
			case FrameType.Open:
				throw new ProtocolError("OPEN is server-to-client only");
			case FrameType.Head: {
				let head: HeadMessage;
				let headers: Headers;
				try {
					head = decodeHead(payload);
					// Built here because the runtime rejects header names and values it cannot send.
					headers = http
						? publicResponseHeaders(head.headers, head.body)
						: publicResponseHeaders(stripWebSocketHandshake(head.headers), false);
				} catch {
					// A bad response from one local request fails that request, not the whole tunnel.
					this.sendFrame(FrameType.Reset, id, encodeText("invalid response head"));
					if (http) {
						this.fail(http, pages.upstreamFailed);
					}
					this.pendingWebSockets.get(id)?.settle(new Response("Invalid response from local server", { status: 502 }));
					this.forgetPending(id);
					return null;
				}
				if (http) {
					if (http.headReceived) {
						throw new ProtocolError("duplicate HEAD");
					}
					http.headReceived = true;
					http.settleHead({ ok: true, head, headers });
				} else {
					this.settleWebSocket(id, head, headers);
				}
				return null;
			}
			case FrameType.Data:
			case FrameType.Text: {
				if (http) {
					return this.receiveBody(http, frame);
				}
				const publicSocket = this.publicSocket(id);
				if (publicSocket?.readyState === WebSocket.OPEN) {
					const breach = this.recordPublicWsMessage(payload.byteLength);
					if (breach) {
						return breach;
					}
					publicSocket.send(frame.type === FrameType.Text ? decodeText(payload) : payload);
				}
				return null;
			}
			case FrameType.End: {
				if (http) {
					http.ended = true;
					this.flush(http);
					return null;
				}
				const close = decodeClose(payload);
				const publicSocket = this.publicSocket(id);
				if (publicSocket) {
					safeClose(publicSocket, close.code, close.reason);
				}
				return null;
			}
			case FrameType.Reset: {
				if (http) {
					this.fail(http, pages.upstreamFailed);
					return null;
				}
				const pending = this.pendingWebSockets.get(id);
				if (pending) {
					this.forgetPending(id);
					pending.settle(new Response("Local WebSocket unavailable", { status: 502 }));
					return null;
				}
				const publicSocket = this.publicSocket(id);
				if (publicSocket) {
					safeClose(publicSocket, 1011, decodeText(payload));
				}
				return null;
			}
			case FrameType.Window: {
				const bytes = decodeWindow(payload);
				if (http) {
					http.sendCredit += bytes;
					http.wakeUploader?.();
				}
				return null;
			}
		}
	}

	private sendFrame(type: FrameType, id: number, payload?: Uint8Array): void {
		const client = this.client();
		if (client) {
			client.send(encodeFrame(type, id, payload));
		}
	}

	/**
	 * Stream ids only ever increase for the lifetime of the tunnel, including across hibernation,
	 * so a late frame can never be mistaken for a newer stream.
	 */
	private async allocateStream(): Promise<number> {
		// One shared load, so concurrent first requests after waking cannot both start from the same id.
		this.streamIdsLoaded ??= this.ctx.storage.get<number>(STREAM_CEILING_KEY).then((ceiling = 1) => {
			this.nextStream = ceiling;
			this.streamCeiling = ceiling;
		});
		await this.streamIdsLoaded;
		const id = this.nextStream++;
		if (id >= this.streamCeiling) {
			this.streamCeiling = id + STREAM_ID_BLOCK;
			// Not awaited: the output gate holds our response until the write is durable.
			void this.ctx.storage.put(STREAM_CEILING_KEY, this.streamCeiling);
		}
		return id;
	}

	private openPublicWebSockets(): WebSocket[] {
		return this.ctx.getWebSockets("public").filter((ws) => ws.readyState === WebSocket.OPEN);
	}

	private publicWebSocketCount(): number {
		return this.pendingWebSockets.size + this.openPublicWebSockets().length;
	}

	private streamCount(): number {
		// A public socket we are closing no longer carries a stream, and its waiters were already woken.
		return this.http.size + this.publicWebSocketCount();
	}

	/**
	 * Waits until the tunnel has a free stream. False when too many requests already wait, none frees
	 * up in time, or the visitor leaves. Bursts of module requests then wait instead of failing a page.
	 */
	private async freeStream(signal: AbortSignal): Promise<boolean> {
		if (signal.aborted || !this.state) {
			return false;
		}
		const { maxStreams, maxWaiting } = this.currentLimits();
		// Requests already waiting go first; this one goes too if a stream is left over.
		const leftOver = maxStreams - this.streamCount() - this.waiting.length;
		this.wakeWaiting();
		if (leftOver > 0) {
			return true;
		}
		if (this.waiting.length >= maxWaiting) {
			return false;
		}
		const deadline = Date.now() + RESPONSE_TIMEOUT_MS;
		let first = false;
		for (;;) {
			if (signal.aborted || !this.state) {
				return false;
			}
			const free = await new Promise<boolean>((resolve) => {
				const timer = setTimeout(() => settle(false), deadline - Date.now());
				const onAbort = () => settle(false);
				const settle = (value: boolean) => {
					clearTimeout(timer);
					signal.removeEventListener("abort", onAbort);
					const index = this.waiting.indexOf(settle);
					if (index >= 0) {
						this.waiting.splice(index, 1);
					}
					resolve(value);
				};
				signal.addEventListener("abort", onAbort, { once: true });
				// Woken but still full: keep its place at the front.
				if (first) {
					this.waiting.unshift(settle);
				} else {
					this.waiting.push(settle);
				}
			});
			if (!free || !this.state) {
				return false;
			}
			if (this.streamCount() < this.currentLimits().maxStreams) {
				return true;
			}
			first = true;
		}
	}

	/** Lets as many waiting requests go as there are free streams. They check again when they run. */
	private wakeWaiting(): void {
		const free = this.currentLimits().maxStreams - this.streamCount();
		if (free > 0 && this.waiting.length > 0) {
			for (const settle of this.waiting.slice(0, free)) {
				settle(true);
			}
		}
	}

	private forgetPending(id: number): void {
		if (this.pendingWebSockets.delete(id)) {
			this.wakeWaiting();
		}
	}

	// ---------------------------------------------------------------------------
	// Public HTTP

	private async proxyHttp(request: Request): Promise<Response> {
		if (!(await this.liveClient())) {
			return this.refuse(request, pages.offline);
		}
		if (!(await this.freeStream(request.signal))) {
			return this.state ? this.refuse(request, pages.busy) : this.missingResponse(request, false);
		}
		// The client or tunnel may have gone while the request waited.
		if (!this.state) {
			return this.missingResponse(request, false);
		}
		if (!this.client()) {
			return this.refuse(request, pages.offline);
		}

		const id = await this.allocateStream();
		if (request.signal.aborted) {
			return new Response(null, { status: 499 });
		}
		const maxRequests = this.currentLimits().maxRequests;
		if (maxRequests !== null && id > maxRequests) {
			await this.terminateLimit("Tunnel request limit reached.");
			return this.refuseLimit(request, false);
		}
		let settleHead!: (result: HeadResult) => void;
		const headResult = new Promise<HeadResult>((resolve) => {
			settleHead = resolve;
		});
		const stream: HttpStream = {
			id,
			settleHead,
			headReceived: false,
			sendCredit: STREAM_WINDOW_BYTES,
			wakeUploader: null,
			uploading: request.body !== null,
			receiveCredit: STREAM_WINDOW_BYTES,
			window: new GrowingWindow(this.windowBudget),
			queue: [],
			pulling: false,
			ended: false,
			controller: null,
			done: false,
		};
		this.http.set(id, stream);

		const url = new URL(request.url);
		this.sendFrame(
			FrameType.Open,
			id,
			encodeOpen({
				method: request.method,
				path: url.pathname + url.search,
				headers: forwardedRequestHeaders(request.headers),
				body: request.body !== null,
			}),
		);
		if (request.body) {
			void this.upload(stream, request.body);
		}
		request.signal.addEventListener("abort", () => this.reset(stream, "public client went away"));

		const result = await withTimeout(headResult, RESPONSE_TIMEOUT_MS);
		if (!result) {
			this.reset(stream, "response timeout");
			return this.refuse(request, pages.timeout);
		}
		if (!result.ok) {
			return this.refuse(request, result.page);
		}

		const { head, headers } = result;
		if (head.status < 200) {
			this.reset(stream, `unsupported status ${head.status}`);
			return this.refuse(request, pages.upstreamFailed);
		}
		if (!head.body || NULL_BODY_STATUSES.has(head.status)) {
			this.finish(stream);
			return new Response(null, { status: head.status, headers });
		}

		const body = new ReadableStream<Uint8Array>(
			{
				start: (controller) => {
					stream.controller = controller;
				},
				pull: () => {
					stream.pulling = true;
					this.flush(stream);
				},
				cancel: () => this.reset(stream, "public client went away"),
			},
			{ highWaterMark: 0 },
		);
		return new Response(body, {
			status: head.status,
			headers,
			// Compressed bodies from the local server are passed through untouched.
			encodeBody: headers.has("content-encoding") ? "manual" : "automatic",
		});
	}

	/** Streams the public request body to the client, never exceeding the granted window. */
	private async upload(stream: HttpStream, body: ReadableStream<Uint8Array>): Promise<void> {
		const reader = body.getReader();
		try {
			for (;;) {
				const { done, value } = await reader.read();
				if (done) {
					break;
				}
				for (let offset = 0; offset < value.byteLength; offset += MAX_CHUNK_BYTES) {
					const chunk = value.subarray(offset, offset + MAX_CHUNK_BYTES);
					while (!stream.done && stream.sendCredit < chunk.byteLength) {
						await new Promise<void>((resolve) => {
							stream.wakeUploader = resolve;
						});
					}
					if (stream.done) {
						await reader.cancel();
						return;
					}
					const breach = this.recordTransferBytes(chunk.byteLength);
					if (breach) {
						await reader.cancel();
						await this.terminateLimit(breach);
						return;
					}
					stream.sendCredit -= chunk.byteLength;
					this.sendFrame(FrameType.Data, stream.id, chunk);
					this.syncUsage();
				}
			}
			stream.uploading = false;
			if (!stream.done) {
				this.sendFrame(FrameType.End, stream.id);
			}
		} catch {
			this.reset(stream, "public request body failed");
		}
	}

	private receiveBody(stream: HttpStream, frame: Frame): string | null {
		if (frame.type !== FrameType.Data || !stream.headReceived || stream.ended) {
			throw new ProtocolError("unexpected response body frame");
		}
		if (frame.payload.byteLength > stream.receiveCredit) {
			throw new ProtocolError("response body exceeded the flow control window");
		}
		const breach = this.recordTransferBytes(frame.payload.byteLength);
		if (breach) {
			return breach;
		}
		stream.receiveCredit -= frame.payload.byteLength;
		// The frame buffer is reused by nothing else, so the payload view can be queued as is.
		stream.queue.push(frame.payload);
		this.flush(stream);
		return null;
	}

	/** Hands queued chunks to the public response as it pulls, returning window to the client. */
	private flush(stream: HttpStream): void {
		const { controller } = stream;
		if (!controller || stream.done) {
			return;
		}
		while (stream.pulling && stream.queue.length > 0) {
			const chunk = stream.queue.shift() as Uint8Array;
			stream.pulling = false;
			controller.enqueue(chunk);
			// Nothing left queued: the visitor has taken everything that arrived.
			const grant = chunk.byteLength + stream.window.delivered(chunk.byteLength, stream.queue.length === 0);
			stream.receiveCredit += grant;
			this.sendFrame(FrameType.Window, stream.id, encodeWindow(grant));
		}
		if (stream.ended && stream.queue.length === 0) {
			controller.close();
			this.finish(stream);
		}
	}

	/** Normal completion of the response. */
	private finish(stream: HttpStream): void {
		if (stream.done) {
			return;
		}
		if (stream.uploading) {
			// The local server answered without reading the whole request body.
			this.sendFrame(FrameType.Reset, stream.id, encodeText("response finished"));
		}
		this.close(stream);
	}

	/** Aborts a stream from our side and tells the client. */
	private reset(stream: HttpStream, reason: string): void {
		if (stream.done) {
			return;
		}
		this.sendFrame(FrameType.Reset, stream.id, encodeText(reason));
		this.fail(stream, pages.upstreamFailed);
	}

	/** Aborts a stream without telling the client (it reset it, or it is gone). */
	/** Answers a request hostc could not serve. */
	private refuse(request: Request, page: PageOptions): Response {
		this.countError(page);
		return errorResponse(request, page);
	}

	private refuseWebSocket(page: PageOptions): Response {
		this.countError(page);
		return new Response(page.title, { status: page.status });
	}

	/** Without this, nobody learns that visitors get errors. Only the kind is kept: no URL, address or tunnel. */
	private countError(page: PageOptions): void {
		this.recordError(page.title);
	}

	private recordError(kind: string, detail?: string): void {
		try {
			this.env.ERRORS.writeDataPoint({
				blobs: detail ? [kind, detail] : [kind],
				indexes: [kind],
			});
		} catch {
			// Analytics Engine write limits must never fail a request.
		}
	}

	private fail(stream: HttpStream, page: PageOptions): void {
		if (stream.done) {
			return;
		}
		// Before the head, the response to the request counts it.
		if (stream.headReceived) {
			this.countError(page);
		}
		stream.settleHead({ ok: false, page });
		try {
			stream.controller?.error(new Error(page.title));
		} catch {
			// Already closed or errored.
		}
		this.close(stream);
	}

	private close(stream: HttpStream): void {
		stream.done = true;
		stream.queue = [];
		this.http.delete(stream.id);
		stream.window.release();
		stream.wakeUploader?.();
		this.wakeWaiting();
	}

	// ---------------------------------------------------------------------------
	// Public WebSockets

	private async proxyWebSocket(request: Request): Promise<Response> {
		if (!(await this.liveClient())) {
			return this.refuseWebSocket(pages.offline);
		}
		if (this.publicWebSocketCount() >= this.currentLimits().maxPublicWebSockets) {
			return this.refuseWebSocket(pages.tooManyWebSockets);
		}
		if (!(await this.freeStream(request.signal))) {
			return this.state ? this.refuseWebSocket(pages.busy) : this.missingResponse(request, false);
		}
		if (!this.state) {
			return this.missingResponse(request, false);
		}
		if (!this.client()) {
			return this.refuseWebSocket(pages.offline);
		}
		if (this.publicWebSocketCount() >= this.currentLimits().maxPublicWebSockets) {
			return this.refuseWebSocket(pages.tooManyWebSockets);
		}

		const offered = parseSubprotocols(request.headers.get("sec-websocket-protocol"));
		if (!offered) {
			return new Response("Invalid Sec-WebSocket-Protocol header", { status: 400 });
		}
		const id = await this.allocateStream();
		if (request.signal.aborted) {
			return new Response(null, { status: 499 });
		}
		const limits = this.currentLimits();
		if (limits.maxRequests !== null && id > limits.maxRequests) {
			await this.terminateLimit("Tunnel request limit reached.");
			return this.refuseLimit(request, true);
		}
		this.usage.publicWsConnections += 1;
		this.syncUsage();
		if (
			limits.maxPublicWebSocketConnections !== null &&
			this.usage.publicWsConnections > limits.maxPublicWebSocketConnections
		) {
			await this.terminateLimit("Tunnel WebSocket connection limit reached.");
			return this.refuseLimit(request, true);
		}
		const accepted = new Promise<Response>((settle) => {
			this.pendingWebSockets.set(id, { offered, settle });
		});

		const url = new URL(request.url);
		this.sendFrame(
			FrameType.Open,
			id,
			encodeOpen({
				method: request.method,
				path: url.pathname + url.search,
				headers: stripWebSocketHandshake(forwardedRequestHeaders(request.headers)),
				body: false,
				websocket: offered,
			}),
		);

		const onAbort = () => {
			const pending = this.pendingWebSockets.get(id);
			if (!pending) {
				return;
			}
			this.forgetPending(id);
			this.sendFrame(FrameType.Reset, id, encodeText("public client went away"));
			pending.settle(new Response(null, { status: 499 }));
		};
		request.signal.addEventListener("abort", onAbort, { once: true });
		try {
			const response = await withTimeout(accepted, RESPONSE_TIMEOUT_MS);
			if (response) {
				return response;
			}
			this.forgetPending(id);
			this.sendFrame(FrameType.Reset, id, encodeText("response timeout"));
			return this.refuseWebSocket(pages.timeout);
		} finally {
			request.signal.removeEventListener("abort", onAbort);
		}
	}

	/**
	 * Runs inside the HEAD frame handler, so the public socket is accepted before
	 * any following DATA frame for this stream is processed.
	 */
	private settleWebSocket(id: number, head: HeadMessage, headers: Headers): void {
		const pending = this.pendingWebSockets.get(id);
		if (!pending) {
			return;
		}
		// Becomes a public socket, or frees its stream.
		this.forgetPending(id);

		if (head.status !== 101) {
			const status = head.status >= 200 && !NULL_BODY_STATUSES.has(head.status) ? head.status : 502;
			pending.settle(new Response(null, { status, headers }));
			return;
		}
		if (head.protocol !== undefined && !pending.offered.includes(head.protocol)) {
			this.sendFrame(FrameType.Reset, id, encodeText("server selected a subprotocol that was not offered"));
			pending.settle(new Response("Invalid WebSocket subprotocol", { status: 502 }));
			return;
		}

		const [client, server] = Object.values(new WebSocketPair()) as [WebSocket, WebSocket];
		this.ctx.acceptWebSocket(server, ["public", `s:${id}`]);
		server.serializeAttachment({ kind: "public", stream: id } satisfies PublicAttachment);
		if (head.protocol) {
			headers.set("sec-websocket-protocol", head.protocol);
		}
		pending.settle(new Response(null, { status: 101, webSocket: client, headers }));
	}

	private fromPublic(ws: WebSocket, id: number, message: string | ArrayBuffer): string | null {
		if (!this.client()) {
			safeClose(ws, 1001, "tunnel disconnected");
			return null;
		}
		const text = typeof message === "string";
		const payload = text ? encodeText(message) : new Uint8Array(message);
		if (payload.byteLength > MAX_WEBSOCKET_MESSAGE_BYTES) {
			safeClose(ws, 1009, "message too big");
			this.sendFrame(FrameType.End, id, encodeClose({ code: 1009, reason: "message too big" }));
			return null;
		}
		const breach = this.recordPublicWsMessage(payload.byteLength);
		if (breach) {
			return breach;
		}
		this.sendFrame(text ? FrameType.Text : FrameType.Data, id, payload);
		return null;
	}

	private publicSocket(id: number): WebSocket | undefined {
		return this.ctx.getWebSockets(`s:${id}`)[0];
	}
}

const NULL_BODY_STATUSES = new Set([101, 204, 205, 304]);

/** Headers of the public request, as the local server should see them. */
export function forwardedRequestHeaders(headers: Headers): HeaderList {
	const list: HeaderList = [];
	for (const [name, value] of headers) {
		if (!name.startsWith("cf-") && name !== "cdn-loop" && name !== "host") {
			list.push([name, value]);
		}
	}
	return stripHopByHop(list);
}

/**
 * Headers of the local response, as the public client should see them.
 * Cookies lose their Domain attribute so a tunnel can only set cookies for its own host.
 */
export function publicResponseHeaders(list: HeaderList, streamed: boolean): Headers {
	const headers = new Headers();
	const extra = streamed ? ["content-length", TUNNEL_MISSING_HEADER] : [TUNNEL_MISSING_HEADER];
	for (const [name, value] of stripHopByHop(list, extra)) {
		if (name.toLowerCase() === "set-cookie") {
			headers.append(name, withoutCookieDomain(value));
			continue;
		}
		headers.append(name, value);
	}
	return headers;
}

/** Drops the Domain attribute, parsed the way browsers do (RFC 6265 §5.2: names are trimmed, case-insensitive). */
export function withoutCookieDomain(cookie: string): string {
	const [pair = "", ...attributes] = cookie.split(";");
	const kept = attributes.filter((attribute) => attribute.split("=")[0]?.trim().toLowerCase() !== "domain");
	return [pair, ...kept].join(";");
}

function attachmentOf(ws: WebSocket): Attachment | null {
	return ws.deserializeAttachment() as Attachment | null;
}

function emptyUsage(): UsageCounters {
	return {
		totalFrames: 0,
		totalBytes: 0,
		publicWsConnections: 0,
		publicWsMessages: 0,
		publicWsBytes: 0,
	};
}

function normalizeUsage(partial: Partial<UsageCounters> | undefined): UsageCounters {
	return {
		totalFrames: partial?.totalFrames ?? 0,
		totalBytes: partial?.totalBytes ?? 0,
		publicWsConnections: partial?.publicWsConnections ?? 0,
		publicWsMessages: partial?.publicWsMessages ?? 0,
		publicWsBytes: partial?.publicWsBytes ?? 0,
	};
}

function maxUsage(a: UsageCounters, b: UsageCounters): UsageCounters {
	return {
		totalFrames: Math.max(a.totalFrames, b.totalFrames),
		totalBytes: Math.max(a.totalBytes, b.totalBytes),
		publicWsConnections: Math.max(a.publicWsConnections, b.publicWsConnections),
		publicWsMessages: Math.max(a.publicWsMessages, b.publicWsMessages),
		publicWsBytes: Math.max(a.publicWsBytes, b.publicWsBytes),
	};
}

function durationLimitReason(ms: number): string {
	if (ms >= 3_600_000 && ms % 3_600_000 === 0) {
		const hours = ms / 3_600_000;
		return `Tunnel ${hours}-hour duration limit reached.`;
	}
	return "Tunnel duration limit reached.";
}

function isStale(ctx: DurableObjectState, client: WebSocket): boolean {
	const attachment = attachmentOf(client);
	const lastSeen =
		ctx.getWebSocketAutoResponseTimestamp(client)?.getTime() ?? (attachment?.kind === "client" ? attachment.since : 0);
	return Date.now() - lastSeen > CLIENT_STALE_MS;
}

function safeClose(ws: WebSocket, code: number, reason: string): void {
	try {
		ws.close(sendableCloseCode(code), sendableCloseReason(reason));
	} catch {
		// Already closing or closed.
	}
}

function withTimeout<T>(promise: Promise<T>, ms: number): Promise<T | undefined> {
	return new Promise((resolve, reject) => {
		const timer = setTimeout(() => resolve(undefined), ms);
		promise.then(
			(value) => {
				clearTimeout(timer);
				resolve(value);
			},
			(error: unknown) => {
				clearTimeout(timer);
				reject(error);
			},
		);
	});
}
